#!/usr/bin/env node
/**
 * Generates supabase/seed.sql from the curated word lists bundled with the app,
 * so the database and the offline game always start from the same vocabulary.
 *
 * Usage: npm run db:seed-sql
 * Requires Node 22.6+ (TypeScript type stripping) — the data files are plain TS.
 */
import { readdirSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const dataDir = join(root, 'src/game/words/data');

const { BUILT_IN_CATEGORIES } = await import(pathToFileURL(join(root, 'src/game/words/categories.ts')).href);

const DIFFICULTY_LEVELS = [
  ['easy', 3, 4, 10, 3, 3, 10, 1],
  ['medium', 5, 6, 20, 3, 5, 15, 2],
  ['hard', 7, 9, 35, 2, 7, 25, 3],
  ['expert', 10, 99, 50, 1, 10, 40, 5],
];

const APP_CONFIG = {
  maxLives: 5,
  lifeRegenMinutes: 20,
  lifeRestoreStreak: 5,
  freeHintsPerDay: 3,
  premiumUnlimitedHints: true,
  premiumCategoryIds: [],
  dailyRewardCoins: [10, 15, 20, 25, 30, 40, 60],
  dailyChallengeCoins: 25,
  adsEnabled: false,
  rewardedAdsEnabled: false,
  premiumEnabled: true,
  progressiveEvery: 5,
};

const q = (value) => (value === null || value === undefined ? 'null' : `'${String(value).replace(/'/g, "''")}'`);

const lines = [
  '-- Generated by scripts/generate-seed.mjs — do not edit by hand.',
  '-- Safe to re-run: existing rows are updated.',
  '',
  'insert into public.categories (id, name, icon, color, is_premium, is_active, sort_order) values',
  BUILT_IN_CATEGORIES.map((c) => `  (${q(c.id)}, ${q(c.name)}, ${q(c.icon)}, ${q(c.color)}, ${c.isPremium}, true, ${c.sortOrder})`).join(',\n'),
  'on conflict (id) do update set name = excluded.name, icon = excluded.icon, color = excluded.color, sort_order = excluded.sort_order;',
  '',
  'insert into public.difficulty_levels (id, min_length, max_length, base_score, max_hints_per_word, timed_penalty_seconds, par_seconds, coin_reward) values',
  DIFFICULTY_LEVELS.map((l) => `  (${q(l[0])}, ${l.slice(1).join(', ')})`).join(',\n'),
  'on conflict (id) do nothing;',
  '',
  'insert into public.app_config (key, value) values',
  Object.entries(APP_CONFIG)
    .map(([k, v]) => `  (${q(k)}, ${q(JSON.stringify(v))}::jsonb)`)
    .join(',\n'),
  'on conflict (key) do nothing;',
  '',
];

let total = 0;
const seen = new Set();
for (const file of readdirSync(dataDir).filter((f) => f.endsWith('.ts')).sort()) {
  const categoryId = file.replace(/\.ts$/, '');
  const { default: raw } = await import(pathToFileURL(join(dataDir, file)).href);
  const rows = [];
  for (const line of raw.split('\n')) {
    const trimmed = line.trim();
    if (!trimmed || trimmed.startsWith('#')) continue;
    const [w, definition, example] = trimmed.split('|').map((p) => p.trim());
    const word = w.normalize('NFKD').toUpperCase().replace(/[^A-Z]/g, '');
    if (word.length < 3 || seen.has(word)) continue;
    seen.add(word);
    rows.push(`  (${q(`en:${word.toLowerCase()}`)}, ${q(word)}, 'en', ${q(categoryId)}, ${q(definition)}, ${q(example || null)}, true)`);
  }
  total += rows.length;
  lines.push(`-- ${categoryId}: ${rows.length} words`);
  lines.push('insert into public.words (id, word, language, category_id, definition, example, is_active) values');
  lines.push(rows.join(',\n'));
  lines.push('on conflict (id) do update set category_id = excluded.category_id, definition = excluded.definition, example = excluded.example;');
  lines.push('');
}

writeFileSync(join(root, 'supabase/seed.sql'), lines.join('\n'));
console.log(`Wrote supabase/seed.sql with ${total} words in ${BUILT_IN_CATEGORIES.length} categories.`);
